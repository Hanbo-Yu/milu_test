export const calculateScores = (answers) => {
  const scores = {}
  const questionScores = { A: 1, B: 2, C: 3, D: 4, E: 5 }
  
  const questions = questionsData['sexual-preference'].questions
  
  questionsData['sexual-preference'].questions.forEach(question => {
    const answer = answers[question.id]
    if (answer) {
      const score = questionScores[answer]
      
      if (!scores[question.dimension]) {
        scores[question.dimension] = { total: 0, count: 0 }
      }
      scores[question.dimension].total += score
      scores[question.dimension].count++
    }
  })
  
  const results = {}
  Object.keys(questionsData['sexual-preference'].results).forEach(dimension => {
    if (scores[dimension]) {
      const avgScore = scores[dimension].total / scores[dimension].count
      results[dimension] = {
        score: parseFloat(avgScore.toFixed(2)),
        level: getScoreLevel(avgScore)
      }
    } else {
      results[dimension] = {
        score: 0,
        level: 'low'
      }
    }
  })
  
  return results
}

const getScoreLevel = (score) => {
  if (score <= 2.33) return 'low'
  if (score <= 3.66) return 'medium'
  return 'high'
}

export const getScoreInterpretation = (dimension, level) => {
  const resultData = questionsData['sexual-preference'].results[dimension]
  if (!resultData) return ''
  
  switch (level) {
    case 'low':
      return resultData.low
    case 'medium':
      return resultData.medium
    case 'high':
      return resultData.high
    default:
      return ''
  }
}
